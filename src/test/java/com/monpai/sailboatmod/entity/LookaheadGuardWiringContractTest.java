package com.monpai.sailboatmod.entity;

import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertTrue;

class LookaheadGuardWiringContractTest {
    @Test
    void regularSailboatStoresTheCompleteRouteButValidatesABoundedWindow() throws Exception {
        String source = sailboat();
        assertTrue(source.contains("AutopilotRouteWindow.complete(route.waypoints())"), "dispatch must retain the true final dock beyond point 512");
        assertTrue(source.contains("AutopilotRouteWindow.around(autopilotRoute, autopilotTargetIndex)"));
        assertTrue(source.contains("AutopilotRouteWindow.apply(autopilotRoute,"));
        assertTrue(source.contains("AutopilotRouteWindow.save(tag, autopilotRoute, autopilotTargetIndex)"));
        assertTrue(source.contains("AutopilotRouteWindow.load(tag)"));
    }

    private static String sailboat() throws Exception {
        return Files.readString(Path.of("src/main/java/com/monpai/sailboatmod/entity/SailboatEntity.java"));
    }

    @Test
    void guardOnlyExistsInTellusWorlds() throws Exception {
        assertTrue(sailboat().contains("TellusWorlds.isTellusLevel("), "the guard is created only in Tellus Earth worlds");
    }

    @Test
    void guardLoadsCorridorChunksAndTicks() throws Exception {
        String src = sailboat();
        assertTrue(src.contains("lookaheadGuard.extraChunks()"), "corridor chunks join the forced autopilot chunks");
        assertTrue(src.contains("lookaheadGuard.tick("), "the guard is ticked with the chunk loading");
    }

    @Test
    void autopilotHoldsWhileDetourIsPending() throws Exception {
        assertTrue(sailboat().contains("lookaheadGuard.shouldHold()"), "the boat stops near the obstacle while waiting");
    }
    @Test
    void guardOnlyWatchesAutoGeneratedWaterRoutes() throws Exception {
        assertTrue(sailboat().contains("WaterAutoRouteService.isGeneratedWaterRouteName(autopilotRouteName)"),
                "manual routes keep the pre-existing behaviour; only auto water routes get the look-ahead");
    }

    @Test
    void guardIsRestoredWhenABoatResumesAfterReload() throws Exception {
        String src = sailboat();
        int loading = src.indexOf("private void updateAutopilotChunkLoading()");
        int next = src.indexOf("private void", loading + 1);
        assertTrue(src.substring(loading, next).contains("ensureLookaheadGuard();"),
                "a boat reloaded mid-trip must get its look-ahead guard back");
    }

    @Test
    void tellusRescueUsesTheStrictLocalPredictorPlannerAndRetainsTheVoyage() throws Exception {
        String src = sailboat();
        assertTrue(src.contains("WaterAutoRouteService.planLocalRescue("),
                "Tellus rescue must use actual NBT/prediction, never noise or a full voyage restart");
        assertTrue(src.contains("next.addAll(original.subList(splice.tailIndex(), original.size()))"));

    }

}
