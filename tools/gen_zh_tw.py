#!/usr/bin/env python3
"""Generate src/main/resources/marketweb/zh-tw.js, the Simplified -> Taiwan Traditional table for the web page.

Needs OpenCC for Python (`pip install opencc-python-reimplemented`). Only the generator needs it; the page
uses the generated table. Re-run after adding Chinese strings; tools/test_zh_tw.js fails until you do.
"""
import json
import pathlib
import re

from opencc import OpenCC

ROOT = pathlib.Path(__file__).resolve().parent.parent
WEB = ROOT / "src/main/resources/marketweb"
SOURCES = ["app.js", "map.js", "logistics-render.js", "logistics-panel.js", "tellus-basemap.js"]
STRING_LITERAL = re.compile(r'"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'|`(?:[^`\\]|\\.)*`')
HAN_RUN = re.compile(r"[一-鿿]+")
# Taiwan usage OpenCC leaves as mainland forms.
# OpenCC's s2twp applies software-term wording (发布 -> 釋出, 类型 -> 型別) that reads wrong for a market.
OVERRIDES = {"賬": "帳", "許可權": "權限", "釋出": "發布", "型別": "類型"}

chars_only = OpenCC("s2tw")
with_phrases = OpenCC("s2twp")


def fix(text):
    for old, new in OVERRIDES.items():
        text = text.replace(old, new)
    return text


runs = set()
for name in SOURCES:
    for literal in STRING_LITERAL.findall((WEB / name).read_text(encoding="utf-8")):
        runs.update(HAN_RUN.findall(literal))

covered = sorted({ch for run in runs for ch in run})
chars = {}
for ch in covered:
    converted = fix(chars_only.convert(ch))
    if converted != ch:
        chars[ch] = converted

MAX_PHRASE = 4


def convert_like_page(run, phrases):
    """What the page does: longest phrase first (up to MAX_PHRASE characters), otherwise one character."""
    out, i = [], 0
    while i < len(run):
        for size in range(min(MAX_PHRASE, len(run) - i), 1, -1):
            piece = run[i:i + size]
            if piece in phrases:
                out.append(phrases[piece])
                i += size
                break
        else:
            out.append(chars.get(run[i], run[i]))
            i += 1
    return "".join(out)


# Words whose Taiwan form is not just the characters converted one by one (设置 -> 設定, 信息 -> 資訊).
phrases = {}
for run in runs:
    for size in range(2, MAX_PHRASE + 1):
        for start in range(0, len(run) - size + 1):
            piece = run[start:start + size]
            converted = fix(with_phrases.convert(piece))
            if len(converted) == len(piece) and converted != "".join(chars.get(ch, ch) for ch in piece):
                phrases[piece] = converted
# Where the segmentation above still disagrees with OpenCC for a whole string, keep OpenCC's answer for it.
for run in sorted(runs):
    expected = fix(with_phrases.convert(run))
    if convert_like_page(run, phrases) != expected:
        phrases[run] = expected
mismatches = [run for run in runs if convert_like_page(run, phrases) != fix(with_phrases.convert(run))]
assert not mismatches, mismatches[:5]

table = json.dumps({"chars": chars, "phrases": phrases, "covered": "".join(covered)}, ensure_ascii=False, sort_keys=True, indent=0)
(WEB / "zh-tw.js").write_text(f"""// Generated by tools/gen_zh_tw.py from the Chinese strings in {", ".join(SOURCES)}. Do not edit by hand.
// Simplified -> Taiwan Traditional for the web page; only interface text is converted, never player data.
(function (root, factory) {{
  const api = factory();
  if (typeof module === "object" && module.exports) {{
    module.exports = api;
  }} else {{
    root.SailboatZhTw = api;
  }}
}})(typeof self !== "undefined" ? self : this, function () {{
  const TABLE = {table};

  const LONGEST = Object.keys(TABLE.phrases).reduce((max, phrase) => Math.max(max, phrase.length), 1);

  /** Longest known phrase first (Taiwan wording such as 設定, 資訊), otherwise character by character. */
  function convertRun(run) {{
    let out = "";
    let i = 0;
    while (i < run.length) {{
      let size = Math.min(LONGEST, run.length - i);
      for (; size > 1; size--) {{
        const phrase = TABLE.phrases[run.slice(i, i + size)];
        if (phrase) {{
          out += phrase;
          break;
        }}
      }}
      if (size <= 1) {{
        out += TABLE.chars[run[i]] || run[i];
        size = 1;
      }}
      i += size;
    }}
    return out;
  }}

  function convert(text) {{
    return String(text == null ? "" : text).replace(/[\\u4e00-\\u9fff]+/g, convertRun);
  }}

  /** A copy of a string dictionary with every value converted. */
  function convertAll(dictionary) {{
    const out = {{}};
    for (const key of Object.keys(dictionary || {{}})) {{
      const value = dictionary[key];
      out[key] = typeof value === "string" ? convert(value) : value;
    }}
    return out;
  }}

  return {{ convert, convertAll, COVERED: TABLE.covered }};
}});
""", encoding="utf-8", newline="\n")
print(f"{len(covered)} characters, {len(chars)} converted, {len(phrases)} phrases")
